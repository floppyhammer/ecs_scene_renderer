#ifndef ESR_ASSET_HANDLE_H
#define ESR_ASSET_HANDLE_H

#include <iostream>
#include <optional>

#include "../utils/uuid.h"

namespace esr {

class AssetId {
public:
    enum class Type {
        /// Invalid.
        None,
        /// For assets created from memory.
        Uuid,
        /// For assets loaded from the file system.
        PathId,
    } type = Type::None;

    AssetId() = default;

    std::optional<Uuid> uuid;

    std::optional<std::string> path_id;

    // Store the uuid/path_id as string. Only for debugging.
    std::string label;

    static AssetId from_file(const std::string& path) {
        AssetId id;
        id.type = AssetId::Type::PathId;
        id.path_id = path;

        std::ostringstream string_stream;
        string_stream << id;
        id.label = string_stream.str();

        return id;
    }

    static AssetId from_random() {
        AssetId id;
        id.type = AssetId::Type::Uuid;
        id.uuid = Uuid::from_random();

        std::ostringstream string_stream;
        string_stream << id;
        id.label = string_stream.str();

        return id;
    }

    inline bool operator==(const AssetId& b) const {
        if (type != b.type) {
            return false;
        }

        switch (type) {
            case Type::Uuid: {
                return uuid.value() == b.uuid.value();
            }
            case Type::PathId: {
                return path_id.value() == b.path_id.value();
            }
            default:
                abort();
        }
    }

    inline bool operator<(const AssetId& b) const {
        if (type != b.type) {
            return type < b.type;
        }

        switch (type) {
            case Type::Uuid: {
                return uuid.value() < b.uuid.value();
            }
            case Type::PathId: {
                return path_id.value() < b.path_id.value();
            }
            default:
                abort();
        }
    }

    friend std::ostream& operator<<(std::ostream& os, const AssetId& id) {
        switch (id.type) {
            case Type::Uuid: {
                os << "AssetId (Uuid) " << id.uuid.value();
            } break;
            case Type::PathId: {
                os << "AssetId (Path id) " << id.path_id.value();
            } break;
            default:
                abort();
        }
        return os;
    }
};

template <typename T>
class C_AssetHandleWeak {
public:
    C_AssetHandleWeak() = default;

    C_AssetHandleWeak(AssetId id, std::shared_ptr<T> data) : _id(id), _data(data) {};

    std::shared_ptr<T> get_data() {
        if (_data.expired()) {
            return nullptr;
        }

        return _data.lock();
    }

    AssetId get_id() const {
        return _id;
    }

    std::string get_type() const {
        return typeid(T).name();
    }

    void print() const {
        std::cout << _id << std::endl;
    }

    bool operator<(const C_AssetHandleWeak& rhs) const {
        return _id < rhs._id;
    }

    bool operator==(const C_AssetHandleWeak& rhs) const {
        return _id == rhs._id;
    }

private:
    AssetId _id;
    std::weak_ptr<T> _data;
};

template <typename T>
class R_Assets;

/// Asset handle which is always generated by Assets<T>.
template <typename T>
class C_AssetHandle {
    friend class R_Assets<T>;

public:
    C_AssetHandle() = default;

    C_AssetHandleWeak<T> as_weak() const {
        return {_id, _data};
    }

    inline bool operator<(const C_AssetHandle& rhs) const {
        return _id < rhs._id;
    }

    inline bool operator==(const C_AssetHandle& rhs) const {
        return _id == rhs._id;
    }

    AssetId get_id() const {
        return _id;
    }

    std::string get_type() const {
        return typeid(T).name();
    }

    void print() const {
        std::cout << _id << std::endl;
    }

    std::shared_ptr<T> get_data() {
        return _data;
    }

    void mark_as_modified(bool modified) {
        _modified = modified;
    }

    bool is_modified() const {
        return _modified;
    }

private:
    /// Create handle with data and a random uuid.
    explicit C_AssetHandle(std::shared_ptr<T> data) {
        _id = AssetId::from_random();
        _data = data;
    }

    /// Create handle with data and a specific uuid.
    C_AssetHandle(AssetId id, std::shared_ptr<T> data) {
        _id = id;
        _data = data;
    }

private:
    /// Unique ID created upon asset creation.
    AssetId _id;
    /// Holding actual data.
    std::shared_ptr<T> _data;

    bool _modified = true;
};

} // namespace esr

#endif // ESR_ASSET_HANDLE_H
